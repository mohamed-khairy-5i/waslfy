/**
 * توكنايزشن + قوائم الكلمات الدالة المشتركة بين المستخرجات.
 */
import { AR_LETTER } from './normalize';

export const LETTER_CLASS = 'A-Za-z\\u0621-\\u064A';
const WORD_RE = new RegExp(`[${LETTER_CLASS}0-9]+`, 'g');

export interface Token {
  text: string;
  start: number;
  end: number;
}

/** تقطيع نص التطبيع لتوكِنات (حروف/أرقام متتالية) مع حفظ المواضع. */
export function tokenize(search: string): Token[] {
  const tokens: Token[] = [];
  for (const m of search.matchAll(WORD_RE)) {
    tokens.push({ text: m[0], start: m.index, end: m.index + m[0].length });
  }
  return tokens;
}

export interface Segment {
  start: number;
  end: number;
}

/** تقسيم النص لمقاطع على الفواصل — ، , | ; / وسطر جديد. */
export function segmentRanges(search: string): Segment[] {
  const segs: Segment[] = [];
  let start = 0;
  for (let i = 0; i < search.length; i++) {
    const ch = search[i];
    if (ch === ',' || ch === '|' || ch === ';' || ch === '\n' || ch === '/') {
      segs.push({ start, end: i });
      start = i + 1;
    }
  }
  segs.push({ start, end: search.length });
  return segs.filter((s) => s.end > s.start);
}

export function isLetters(t: string): boolean {
  return /^[A-Za-z\u0621-\u064A]+$/.test(t);
}

